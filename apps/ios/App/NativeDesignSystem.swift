// Artboard coordinates are points. Align actual system-font baselines, not
// guessed bounding-box padding. Dynamic type still measures and wraps Text.
struct NativeTextBaseline: Layout {
  let size: CGFloat
  let lineHeight: CGFloat
  var baselineOffset: CGFloat = 0
  var centered = false
  func sizeThatFits(proposal: ProposedViewSize, subviews: Subviews, cache: inout ()) -> CGSize {
    let dimensions = subviews[0].dimensions(in: proposal)
    return CGSize(
      width: proposal.width ?? dimensions.width,
      height: lineHeight + max(0, dimensions[.lastTextBaseline] - dimensions[.firstTextBaseline]))
  }
  func placeSubviews(
    in bounds: CGRect, proposal: ProposedViewSize, subviews: Subviews, cache: inout ()
  ) {
    let offered = ProposedViewSize(width: bounds.width, height: nil)
    let dimensions = subviews[0].dimensions(in: offered)
    subviews[0].place(
      at: CGPoint(
        x: bounds.minX + (centered ? max(0, bounds.width - dimensions.width) / 2 : 0),
        y: bounds.minY + size * 0.93 + baselineOffset - dimensions[.firstTextBaseline]),
      anchor: .topLeading, proposal: offered)
  }
}
struct NativeText: View {
  let value: String
  let bold: Bool
  let baseSize: CGFloat
  let requestedLineHeight: CGFloat?
  let explicitLineWidth: CGFloat?
  let trackingCorrection: CGFloat
  let baselineAdjustment: CGFloat
  let centered: Bool
  let opticalTrailingPunctuation: Bool
  @ScaledMetric(relativeTo: .body) private var size: CGFloat = 17
  init(
    _ value: String, size: CGFloat, bold: Bool = false, lineHeight: CGFloat? = nil,
    explicitLineWidth: CGFloat? = nil, trackingCorrection: CGFloat = 0,
    baselineAdjustment: CGFloat = 0, centered: Bool = false,
    opticalTrailingPunctuation: Bool = false
  ) {
    self.value = value
    self.bold = bold
    baseSize = size
    requestedLineHeight = lineHeight
    self.explicitLineWidth = explicitLineWidth
    self.trackingCorrection = trackingCorrection
    self.baselineAdjustment = baselineAdjustment
    self.centered = centered
    self.opticalTrailingPunctuation = opticalTrailingPunctuation
    _size = ScaledMetric(wrappedValue: size, relativeTo: .body)
  }
  private var displayedValue: String {
    guard let width = explicitLineWidth, abs(size - baseSize) < 0.01 else { return value }
    return Self.wrappedValue(value, width: width, size: size, bold: bold)
  }
  static func wrappedValue(_ value: String, width: CGFloat, size: CGFloat, bold: Bool) -> String {
    var result = ""
    var advance: CGFloat = 0
    for character in value {
      if character.isNewline {
        result.append(character)
        advance = 0
        continue
      }
      let glyphWidth =
        character.unicodeScalars.contains { $0.value > 255 && $0.value != 8226 }
        ? size : NativeLatinAdvances.width(String(character), size: size, bold: bold)
      if advance > 0 && advance + glyphWidth > width {
        result.append("\n")
        advance = 0
      }
      result.append(character)
      advance += glyphWidth
    }
    return result
  }
  private func nativeText(_ text: String) -> Text {
    let nativeFont = UIFont.systemFont(ofSize: size, weight: bold ? .bold : .regular)
    let chinese = Font.custom(
      bold ? "PingFangSC-Semibold" : "PingFangSC-Regular", fixedSize: size)
    var result: Text?
    var run = ""
    var isChinese: Bool?
    func appendRun() {
      guard !run.isEmpty else { return }
      if isChinese == true {
        // Preserve native PingFang outlines and point size. Optical spacing
        // and the CJK baseline are calibrated independently of the SF run.
        let part = Text(run).font(chinese)
          .tracking(
            (!bold
              ? (baseSize == 14 && value == "复制地址" ? 0.6 * size / 14 : 0)
              : ((baseSize == 17 || baseSize == 21)
                && value.range(of: "[A-Za-z]", options: .regularExpression) == nil)
                ? 0 : (baseSize == 26 && value.hasPrefix("SwiftUI")) ? -size / 520 : -size / 130)
              + trackingCorrection * size / baseSize / CGFloat(max(1, value.count))
          )
          .baselineOffset(bold ? -size / 52 : 0)
        result = result.map { $0 + part } ?? part
      } else {
        let expected =
          NativeLatinAdvances.width(run, size: baseSize, bold: bold) * size / baseSize
        let measured = (run as NSString).size(withAttributes: [.font: nativeFont, .kern: 0]).width
        let part = Text(run).font(.system(size: size, weight: bold ? .bold : .regular))
          .tracking(
            (expected - measured + opticalCorrection(run)) / CGFloat(run.count) + trackingCorrection
              * size / baseSize / CGFloat(max(1, value.count)))
        result = result.map { $0 + part } ?? part
      }
    }
    for character in text {
      let chineseCharacter = character.unicodeScalars.contains {
        $0.value > 255 && $0.value != 8226 && $0.value != 8211
      }
      if isChinese != nil && isChinese != chineseCharacter {
        appendRun()
        run = ""
      }
      isChinese = chineseCharacter
      run.append(character)
    }
    appendRun()
    return result ?? Text("").font(.system(size: size))
  }
  // Residual SwiftUI run widths measured from native captures, in points.
  // This adjusts spacing only; no font substitution or geometric scaling.
  private func opticalCorrection(_ run: String) -> CGFloat {
    let correction: CGFloat
    if !bold && baseSize == 17
      && run.range(of: "\\.(md|markdown|srt|pdf|png|mp4)$", options: .regularExpression) != nil
    {
      correction =
        run.hasSuffix("article.md")
        ? 1.5 : run.hasSuffix("subtitles.srt") ? 2.2 : run.hasSuffix("recording.mp4") ? 2 : 3
    } else if !bold && baseSize == 15 && run == "example.com/swiftui" {
      correction = -2.5
    } else if !bold && baseSize == 15 && run.contains("/")
      && run.range(of: "\\.(md|srt)$", options: .regularExpression) != nil
    {
      correction = 1.5
    } else if !bold && baseSize == 16 && run.contains("Markdown") {
      correction = 2.5
    } else if !bold && baseSize == 13 && (run.contains(" KB") || run.contains(" MB")) {
      correction = 0
    } else if bold && baseSize == 26 && run.contains("SwiftUI") {
      correction = -0.9
    } else if bold && baseSize == 17 && run.contains("Markdown") {
      correction = 1.5
    } else if !bold && baseSize == 12
      && run.range(of: "\\.(md|txt|srt):", options: .regularExpression) != nil
    {
      correction = 2.2
    } else if !bold && baseSize == 16 && run.contains("SwiftUI") {
      correction = 0.8
    } else if !bold && baseSize == 12 {
      correction = 2
    } else if !bold && baseSize == 13 {
      correction = 1.5
    } else if !bold && baseSize == 15 && run.contains("https://") {
      correction = 4
    } else if !bold && baseSize == 14 && run.contains(".") {
      correction = 1.5
    } else {
      correction = 0
    }
    return correction * size / baseSize
  }
  private var lineHeight: CGFloat { (requestedLineHeight ?? baseSize * 1.42) * size / baseSize }
  private func singleLine(_ text: String) -> some View {
    NativeTextBaseline(
      size: size, lineHeight: lineHeight, baselineOffset: baselineAdjustment * size / baseSize,
      centered: centered
    ) {
      nativeText(text).font(.system(size: size, weight: bold ? .bold : .regular))
        .fixedSize(horizontal: false, vertical: true)
    }
  }
  @ViewBuilder private func line(_ text: String) -> some View {
    if (baseSize == 14 || baseSize == 16 || baseSize == 17) && !bold && text.hasSuffix("。") {
      let prefix = String(text.dropLast())
      // Heiti's full stop is centered higher/rightward in the em square.
      // Place the native PingFang glyph optically; its shape/size stays native.
      NativePunctuationLayout(
        advance: prefix.reduce(CGFloat(0)) { advance, character in
          advance
            + (character.unicodeScalars.contains { $0.value > 255 && $0.value != 8226 }
              ? size
              : NativeLatinAdvances.width(String(character), size: baseSize, bold: bold) * size
                / baseSize)
        }, size: size, lineHeight: lineHeight
      ) {
        singleLine(prefix)
        singleLine("。")
      }
    } else {
      singleLine(text)
    }
  }
  var body: some View {
    if bold && baseSize == 18 && value.hasSuffix("？") && abs(size - baseSize) < 0.01 {
      NativeTrailingGlyphLayout(opticalAdvance: 3.5) {
        singleLine(value).hidden().accessibilityHidden(true)
        singleLine(String(value.dropLast()))
        singleLine("？")
      }.accessibilityElement(children: .ignore).accessibilityLabel(value)
    } else if opticalTrailingPunctuation && value.hasSuffix("。") && abs(size - baseSize) < 0.01 {
      line(value)
    } else if explicitLineWidth != nil && abs(size - baseSize) < 0.01 {
      // The accepted mockup wraps per character, including punctuation.
      // Separate native Text lines preserve its 20pt baseline pitch exactly.
      VStack(alignment: .leading, spacing: 0) {
        ForEach(Array(displayedValue.components(separatedBy: "\n").enumerated()), id: \.offset) {
          _, value in
          line(value)
        }
      }.accessibilityElement(children: .combine).accessibilityLabel(value)
    } else {
      NativeTextBaseline(
        size: size, lineHeight: lineHeight, baselineOffset: baselineAdjustment * size / baseSize,
        centered: centered
      ) {
        nativeText(value).font(.system(size: size, weight: bold ? .bold : .regular))
          .lineSpacing(
            requestedLineHeight.map {
              $0 * size / baseSize
                - (UIFont(name: bold ? "PingFangSC-Semibold" : "PingFangSC-Regular", size: size)?
                  .lineHeight ?? size * 1.42)
            } ?? 0
          )
          .fixedSize(horizontal: false, vertical: true)
      }
    }
  }
}
private struct NativeTrailingGlyphLayout: Layout {
  let opticalAdvance: CGFloat
  func sizeThatFits(proposal: ProposedViewSize, subviews: Subviews, cache: inout ()) -> CGSize {
    subviews[0].sizeThatFits(proposal)
  }
  func placeSubviews(
    in bounds: CGRect, proposal: ProposedViewSize, subviews: Subviews, cache: inout ()
  ) {
    subviews[0].place(at: bounds.origin, anchor: .topLeading, proposal: .unspecified)
    subviews[1].place(at: bounds.origin, anchor: .topLeading, proposal: .unspecified)
    subviews[2].place(
      at: CGPoint(
        x: bounds.minX + subviews[1].sizeThatFits(.unspecified).width + opticalAdvance,
        y: bounds.minY),
      anchor: .topLeading, proposal: .unspecified)
  }
}
private struct NativePunctuationLayout: Layout {
  let advance: CGFloat
  let size: CGFloat
  let lineHeight: CGFloat
  func sizeThatFits(proposal: ProposedViewSize, subviews: Subviews, cache: inout ()) -> CGSize {
    .init(width: proposal.width ?? advance + size, height: lineHeight)
  }
  func placeSubviews(
    in bounds: CGRect, proposal: ProposedViewSize, subviews: Subviews, cache: inout ()
  ) {
    subviews[0].place(at: bounds.origin, anchor: .topLeading, proposal: .unspecified)
    subviews[1].place(
      at: .init(
        x: bounds.minX + advance + 3 * size / 14,
        y: bounds.minY - 4.5 * size / 14), anchor: .topLeading, proposal: .unspecified)
  }
}
// Keep the accepted short-content coordinates. Longer content and larger
// fonts expand the row from measured text instead of painting over its footer.
struct NativeLibraryLayout: Layout {
  let height: CGFloat
  let scale: CGFloat
  private func measurements(_ width: CGFloat, _ subviews: Subviews) -> (
    sizes: [CGSize], summaryY: CGFloat, footerY: CGFloat, total: CGFloat, stackedFooter: Bool
  ) {
    let title = subviews[0].sizeThatFits(.init(width: width - 91, height: nil))
    let summary = subviews[1].sizeThatFits(.init(width: width - 72, height: nil))
    let status = subviews[3].sizeThatFits(.unspecified)
    let availableDateWidth = max(1, width - 68 - status.width - 8)
    let stackedFooter = scale > 1.001
      || subviews[2].sizeThatFits(.unspecified).width > availableDateWidth
    let dateWidth = stackedFooter ? max(1, width - 68) : availableDateWidth
    let date = subviews[2].sizeThatFits(.init(width: dateWidth, height: nil))
    let flows = scale > 1.001 || stackedFooter || title.height > 49
      || summary.height > (height > 115 ? 40.5 : 20.5)
    let summaryY = flows ? max(66, 17 + title.height + 12) : 66
    let footerY = flows ? max(height - 25, summaryY + summary.height + 12) : height - 25
    let footerHeight = stackedFooter ? date.height + 8 + status.height : max(date.height, status.height)
    let total = flows ? max(height, footerY + footerHeight + 12) : height
    return ([title, summary, date, status], summaryY, footerY, total, stackedFooter)
  }
  func sizeThatFits(proposal: ProposedViewSize, subviews: Subviews, cache: inout ()) -> CGSize {
    let width = proposal.width ?? 393
    return .init(width: width, height: measurements(width, subviews).total)
  }
  func placeSubviews(
    in bounds: CGRect, proposal: ProposedViewSize, subviews: Subviews, cache: inout ()
  ) {
    let m = measurements(bounds.width, subviews)
    let positions: [CGPoint] = [
      .init(x: 52, y: 17), .init(x: 52, y: m.summaryY), .init(x: 52, y: m.footerY),
      m.stackedFooter
        ? .init(x: 52, y: m.footerY + m.sizes[2].height + 8)
        : .init(x: bounds.width - 16 - m.sizes[3].width, y: m.footerY),
    ]
    for index in subviews.indices {
      subviews[index].place(
        at: .init(x: bounds.minX + positions[index].x, y: bounds.minY + positions[index].y),
        anchor: .topLeading,
        proposal: .init(width: m.sizes[index].width, height: m.sizes[index].height))
    }
  }
}
