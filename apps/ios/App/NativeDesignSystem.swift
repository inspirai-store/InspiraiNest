enum NativeFontMetrics {
  static func inputTracking(_ text: String, size: CGFloat, baseSize: CGFloat) -> CGFloat {
    guard !text.isEmpty else { return 0 }
    let reference = text.reduce(CGFloat.zero) { result, character in
      let value = String(character)
      if value == "•" { return result + 9.6953125 * size / 16 }
      if character.unicodeScalars.contains(where: { $0.value > 255 && $0.value != 8226 }) {
        return result + size
      }
      return result + NativeLatinAdvances.width(value, size: baseSize, bold: false) * size
        / baseSize
    }
    let measured = (text as NSString).size(withAttributes: [
      .font: UIFont.systemFont(ofSize: size), .kern: 0,
    ]).width
    // Native TextField retains optical kerning after View.tracking. These
    // residual run advances come from the original iPhone/iPad captures.
    let residual: CGFloat =
      text.contains("https://")
      ? 7 : text.range(of: "[A-Za-z]", options: .regularExpression) != nil ? 1 : 0
    return (reference - measured + residual * size / baseSize) / CGFloat(text.count)
  }
