import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRegistry} from '../../packages/plugin-sdk/runtime.mjs';
const root = fileURLToPath(new URL('../../',import.meta.url));
const manifests = fs.readdirSync(path.join(root,'plugins'),{withFileTypes:true}).filter(item=>item.isDirectory()).map(item=>item.name).sort().map(id => JSON.parse(fs.readFileSync(path.join(root,'plugins',id,'plugin.json'),'utf8')));
createRegistry(manifests);
const output = '// Generated by tooling/plugins/generate.mjs. Edit plugins/*/plugin.json.\nexport const manifests = ' + JSON.stringify(manifests,null,2) + ';\n';
const target = path.join(root,'packages/plugin-sdk/catalog.mjs');
if (process.argv.includes('--check')) { if (!fs.existsSync(target) || fs.readFileSync(target,'utf8') !== output) throw new Error('Plugin catalog is stale'); }
else fs.writeFileSync(target,output);

const fixture={protocol:1,revision:1,enabled:Object.fromEntries(manifests.map(p=>[p.id,p.defaultEnabled])),plugins:manifests.map(p=>({...p,enabled:p.defaultEnabled}))};
const fixtureTarget=path.join(root,'tests/fixtures/plugins.json'),fixtureOutput=JSON.stringify(fixture,null,2)+'\n';
if(process.argv.includes('--check')){if(!fs.existsSync(fixtureTarget)||fs.readFileSync(fixtureTarget,'utf8')!==fixtureOutput)throw Error('Plugin fixture is stale');}
else{fs.mkdirSync(path.dirname(fixtureTarget),{recursive:true});fs.writeFileSync(fixtureTarget,fixtureOutput);}
